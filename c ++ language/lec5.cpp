# include<iostream>
/* code for adding two numbers */
int main() {
    int num1, num2;

    /* '<<' is called insertion operator */
    /* '>>' is called extraction operator */

 std ::cout<<"enter the value of num1 :\n";
 std ::cin>>num1;

 std ::cout<<" enter the value of num2 :\n";
 std ::cin>>num2;

 std ::cout<<" The sum of numbers = "<< num1+num2;

 return 0;

 
}